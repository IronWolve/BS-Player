/// All 67 named palettes, including the original Light and Dark palettes.
pub fn catalogue() -> &'static [Palette] {
    &BUILTIN
}

/// Look up a saved theme ID. `system` is a mode, not a named color palette.
pub fn find(id: &str) -> Option<&'static Palette> {
    BUILTIN.iter().find(|palette| palette.id == id)
}

/// Resolve the persisted choice to egui's light/dark style family.
pub fn effective_theme(id: &str, system_dark: bool) -> &'static str {
    if id == "system" {
        return if system_dark { "dark" } else { "light" };
    }
    find(id).map_or(
        "light",
        |palette| if palette.dark { "dark" } else { "light" },
    )
}

/// Palette foreground corrected only when its source color misses 4.5:1
/// contrast against one of its two main surfaces.
pub fn normal_text(palette: &Palette) -> [u8; 3] {
    let on_surfaces = |text| [palette.bg, palette.panel, palette.panel2]
        .into_iter().map(|surface| contrast(text, surface)).fold(f32::INFINITY, f32::min);
    if on_surfaces(palette.text) >= 4.5 {
        return palette.text;
    }
    let black = [0, 0, 0];
    let white = [255, 255, 255];
    let target = if on_surfaces(black) >= on_surfaces(white)
    {
        black
    } else {
        white
    };
    for amount in 1..=100 {
        let candidate = std::array::from_fn(|i| {
            (palette.text[i] as f32 * (1.0 - amount as f32 / 100.0)
                + target[i] as f32 * amount as f32 / 100.0)
                .round() as u8
        });
        if on_surfaces(candidate) >= 4.5 {
            return candidate;
        }
    }
    palette.text
}

/// Black or white text with the stronger contrast on the selection fill.
pub fn selected_text(palette: &Palette) -> [u8; 3] {
    let black = [0, 0, 0];
    let white = [255, 255, 255];
    let source = match palette.on_text {
        "black" => Some(black),
        "white" => Some(white),
        value if value.len() == 7 && value.starts_with('#') => {
            let r = u8::from_str_radix(&value[1..3], 16).ok();
            let g = u8::from_str_radix(&value[3..5], 16).ok();
            let b = u8::from_str_radix(&value[5..7], 16).ok();
            r.zip(g).zip(b).map(|((r, g), b)| [r, g, b])
        }
        _ => None,
    };
    if let Some(source) = source.filter(|color| contrast(*color, palette.on) >= 4.5) {
        return source;
    }
    if contrast(black, palette.on) >= contrast(white, palette.on) {
        black
    } else {
        white
    }
}

fn contrast(a: [u8; 3], b: [u8; 3]) -> f32 {
    let luminance = |rgb: [u8; 3]| {
        let mut c = rgb.map(|v| v as f32 / 255.0);
        for value in &mut c {
            *value = if *value <= 0.04045 {
                *value / 12.92
            } else {
                ((*value + 0.055) / 1.055).powf(2.4)
            };
        }
        0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
    };
    let (hi, lo) = {
        let x = luminance(a);
        let y = luminance(b);
        (x.max(y), x.min(y))
    };
    (hi + 0.05) / (lo + 0.05)
}
